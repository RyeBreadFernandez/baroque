/// A dot-matrix stamp. `pitch` is the dot spacing; the stamp is 7 dots tall.
struct NRDotStamp: View {
    var text: String
    var color: Color
    var pitch: CGFloat = 1.3
    var glow: Double = 0.7
    var seed: UInt64 = 1

    var body: some View {
        let t = text.uppercased()
        let w = CGFloat(NRDotFont.columns(t)) * pitch
        let h = 7 * pitch
        let pad: CGFloat = 6
        Canvas { ctx, _ in
            var rng = SeededRandom(seed: seed &+ UInt64(t.count) &* 131)
            var dots = Path()
            var faint = Path()
            for (i, ch) in t.enumerated() {
                guard let rows = NRDotFont.rows[ch] ?? NRDotFont.rows[" "] else { continue }
                // Each character lands a hair off the line, as an inkjet head drifts.
                let dy = rng.range(-0.18...0.18) * pitch
                for (r, row) in rows.enumerated() {
                    for (c, cell) in row.enumerated() where cell == "#" {
                        let x = pad + (CGFloat(i * 6 + c) + 0.5) * pitch + rng.range(-0.08...0.08) * pitch
                        let y = pad + (CGFloat(r) + 0.5) * pitch + dy + rng.range(-0.08...0.08) * pitch
                        let rad = pitch * rng.range(0.36...0.47)
                        let dot = Path(ellipseIn: CGRect(x: x - rad, y: y - rad, width: rad * 2, height: rad * 2))
                        if rng.unit() < 0.06 { faint.addPath(dot) } else { dots.addPath(dot) }
                    }
                }
            }
            var add = ctx
            add.blendMode = .plusLighter
            add.drawLayer { l in
                l.addFilter(.blur(radius: pitch * 1.6))
                l.fill(dots, with: .color(color.opacity(glow)))
            }
            ctx.fill(dots, with: .color(color))
            ctx.fill(faint, with: .color(color.opacity(0.35)))
            // Hot centres.
            ctx.drawLayer { l in
                l.opacity = 0.55
                l.fill(dots.applying(.init(translationX: 0, y: 0)), with: .color(.white.opacity(0.35)))
            }
        }
        .frame(width: w + pad * 2, height: h + pad * 2)
        .padding(-pad)
        .frame(width: w, height: h)
    }
}
